function t(key, lang, fallback = '') {
  const parts = key.split('.');
  let node = I18N[lang] || I18N.en;
  for (const p of parts) {
    if (!node || typeof node !== 'object') return fallback || key;
    node = node[p];
  }
  return node ?? fallback ?? key;
}

if (typeof window !== 'undefined') {
  window.I18N = I18N;
  window.t = t;
}
